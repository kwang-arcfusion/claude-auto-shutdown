import {
  app,
  BrowserWindow,
  ipcMain,
  Menu,
  nativeImage,
  nativeTheme,
  Notification,
  powerMonitor,
  powerSaveBlocker,
  session,
  shell,
  Tray,
  type IpcMainInvokeEvent,
  type MenuItemConstructorOptions,
  type NativeImage,
} from 'electron';
import { writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { msg, render, translate, type Message, type MessageCode } from '../shared/i18n';
import type { DetectionResult, Phase, Settings } from '../shared/types';
import { buildActionCommand, runActionCommand } from './actions';
import { Controller } from './controller';
import { ClaudeDetector, defaultClaudeDir, resolveClaudeDir, type Detector } from './detector/claude';
import { PowerShellSnapshotter } from './detector/processes';
import { renderAppIcon, type Rgb } from './icon';
import { KeepAwake } from './keep-awake';
import { openLogStore } from './log-store';
import { loadSettings, saveSettings } from './storage';

// ---- command-line flags ----------------------------------------------------------
const argv = process.argv.slice(1);
const hasFlag = (name: string): boolean => argv.includes(`--${name}`);
const flagValue = (name: string): string | undefined => {
  const prefix = `--${name}=`;
  return argv.find((arg) => arg.startsWith(prefix))?.slice(prefix.length);
};

/** Starts in the tray without a window. */
const START_HIDDEN = hasFlag('hidden');
// Test hooks.
const SMOKE = hasFlag('smoke'); // print one detection as JSON and exit
const CAPTURE_FILE = flagValue('capture'); // save a screenshot of the window
const CAPTURE_DELAY_MS = Number(flagValue('capture-delay') ?? 2500);
const EXIT_AFTER_MS = flagValue('exit-after') !== undefined ? Number(flagValue('exit-after')) : null;
const USER_DATA = flagValue('user-data');
const EXPAND = hasFlag('expand'); // open the collapsed sections before capturing
const FAKE_DETECTOR = flagValue('fake-detector');
const TEST_MODE = SMOKE || CAPTURE_FILE !== undefined || EXIT_AFTER_MS !== null || FAKE_DETECTOR !== undefined;
/** Never runs the real action; only logs it. Every test flag implies it, so a test run can never shut the PC down. */
const DRY_RUN_FORCED = hasFlag('dry-run') || TEST_MODE;
const AUTO_ARM = hasFlag('auto-arm') && DRY_RUN_FORCED;

if (USER_DATA) app.setPath('userData', path.resolve(USER_DATA));
else if (TEST_MODE) app.setPath('userData', path.join(os.tmpdir(), 'claude-auto-shutdown-test'));

// A small static UI does not need the GPU; without it the app uses far less memory and CPU.
app.disableHardwareAcceleration();
app.setAppUserModelId('local.claude-auto-shutdown');

if (!TEST_MODE && !app.requestSingleInstanceLock()) {
  app.quit();
} else {
  main();
}

function fakeDetector(mode: string): Detector {
  const busy = mode === 'busy';
  return {
    async detect(): Promise<DetectionResult> {
      const now = Date.now();
      return {
        at: now,
        aggregate: busy ? 'busy' : 'idle',
        error: null,
        claudeDir: '(fake detector)',
        usedProcessSnapshot: false,
        durationMs: 1,
        sessions: [
          {
            pid: 4242,
            sessionId: '00000000-0000-0000-0000-000000000000',
            name: busy ? 'Demo: working session' : 'Demo: finished session',
            cwd: 'C:\\Projects\\demo',
            entrypoint: 'claude-desktop',
            status: busy ? 'busy' : 'idle',
            waitingFor: null,
            verdict: busy ? 'working' : 'idle',
            blocksShutdown: busy,
            reason: msg(busy ? 'reason.working' : 'reason.idle'),
            lastActivityAt: now - 4 * 60_000,
            transcriptState: busy ? 'running' : 'ended',
            toolProcesses: [],
            helperCpuPercent: 0,
            processesChecked: true,
          },
        ],
      };
    },
  };
}

/** Tray glyph colour per state (same palette as the UI). */
const TRAY_COLORS: Record<string, Rgb> = {
  disarmed: [142, 150, 161],
  monitoring: [61, 220, 151],
  confirming: [245, 184, 61],
  countdown: [255, 107, 107],
  executing: [211, 58, 58],
};

/** A crashed UI is reloaded, but not more often than this (avoids a crash loop). */
const RELOAD_BACKOFF_MS = 30_000;

function main(): void {
  const userData = app.getPath('userData');
  const settingsFile = path.join(userData, 'settings.json');
  const logs = openLogStore(path.join(userData, 'logs.sqlite'));
  const appIconPath = path.join(__dirname, 'icon.ico'); // generated by scripts/icons.ts

  let mainWindow: BrowserWindow | null = null;
  let tray: Tray | null = null;
  let quitting = false;
  let blockerId: number | null = null;
  let pollTimer: NodeJS.Timeout | null = null;
  let pollThoroughly = false;
  let trayKey = '';
  let onTop = false;
  let toldAboutTray = false;
  let lastReloadAt = 0;
  const icons = new Map<string, NativeImage>();

  // Unattended overnight: log unexpected errors and keep going, never block on an error dialog.
  process.on('uncaughtException', (error) => reportError('app.unexpectedError', error));
  process.on('unhandledRejection', (reason) => reportError('app.unexpectedError', reason));

  const detector: Detector = FAKE_DETECTOR
    ? fakeDetector(FAKE_DETECTOR)
    : new ClaudeDetector({
        claudeDir: () => resolveClaudeDir(controller.getSettings()),
        snapshotter: new PowerShellSnapshotter(userData),
      });

  const controller: Controller = new Controller(
    {
      now: Date.now,
      detect: (settings, thorough) => detector.detect(settings, { skipProcesses: !thorough }),
      runAction: async (settings, dryRun) => {
        const command = buildActionCommand(settings.action, settings.forceCloseApps);
        if (dryRun) return { ok: true, command: command.display };
        return { ...(await runActionCommand(command)), command: command.display };
      },
      describeAction: (settings) => buildActionCommand(settings.action, settings.forceCloseApps).display,
      systemIdleSeconds: () => powerMonitor.getSystemIdleTime(),
      setPreventSleep,
      notify,
      saveSettings: (settings) => saveSettings(settingsFile, settings),
      persistLog: (entry) => logs.store?.append(entry),
      onChange: pushState,
      onCountdownStarted: revealForCountdown,
      defaultClaudeDir: defaultClaudeDir(),
    },
    loadSettings(settingsFile),
    DRY_RUN_FORCED,
  );
  try {
    if (logs.store) controller.restoreLog(logs.store.recent(100));
  } catch (error) {
    reportError('app.oldLogFailed', error); // never stop start-up over old log entries
  }
  const keepAwake = new KeepAwake(userData, (detail) => controller.addLog('warn', 'app.keepAwakeFailed', { detail }));

  /** `code` is a text with a {detail} placeholder for the error message. */
  function reportError(code: MessageCode, error: unknown): void {
    const detail = error instanceof Error ? error.message : String(error);
    try {
      controller.addLog('error', code, { detail });
    } catch {
      // the controller may not exist yet
    }
    process.stderr.write(`${translate('en', code, { detail: error instanceof Error ? (error.stack ?? detail) : detail })}\n`);
  }

  const language = () => controller.getSettings().language;
  const t = (code: MessageCode): string => translate(language(), code);

  function iconFor(key: string): NativeImage {
    let image = icons.get(key);
    if (!image) {
      // The app icon without the moon (unreadable at 16 px), glyph coloured by state.
      const glyph = TRAY_COLORS[key] ?? TRAY_COLORS.disarmed!;
      const render = (size: number): Buffer => renderAppIcon(size, { glyph, moon: false });
      image = nativeImage.createFromBuffer(render(16));
      image.addRepresentation({ scaleFactor: 1.25, buffer: render(20) });
      image.addRepresentation({ scaleFactor: 1.5, buffer: render(24) });
      image.addRepresentation({ scaleFactor: 2, buffer: render(32) });
      icons.set(key, image);
    }
    return image;
  }

  /** Keeps the PC awake while armed: this app stays runnable, and the system stays out of sleep. */
  function setPreventSleep(on: boolean): void {
    if (on && blockerId === null) {
      blockerId = powerSaveBlocker.start('prevent-app-suspension');
      keepAwake.start();
    } else if (!on && blockerId !== null) {
      powerSaveBlocker.stop(blockerId);
      blockerId = null;
      keepAwake.stop();
    }
  }

  function notify(title: Message, body: Message): void {
    // A test run must not alarm whoever is using the PC (e.g. "Shutdown countdown started").
    if (TEST_MODE) return;
    try {
      const lang = language();
      if (Notification.isSupported()) new Notification({ title: render(lang, title), body: render(lang, body), icon: appIconPath }).show();
    } catch {
      // notifications are best effort
    }
  }

  function pushState(): void {
    const state = controller.state();
    if (mainWindow && !mainWindow.isDestroyed()) {
      try {
        mainWindow.webContents.send('state', state);
        const wantOnTop = state.phase === 'countdown' && !TEST_MODE;
        if (wantOnTop !== onTop) {
          onTop = wantOnTop;
          mainWindow.setAlwaysOnTop(wantOnTop);
        }
      } catch {
        // the window is going away; the next state push reaches the new one
      }
    }
    updateTray(state.phase, state.idleSince !== null);
  }

  function updateTray(phase: Phase, confirming: boolean): void {
    if (!tray) return;
    const key = phase === 'monitoring' && confirming ? 'confirming' : phase;
    const lang = language();
    if (`${key}:${lang}` === trayKey) return;
    trayKey = `${key}:${lang}`;
    tray.setImage(iconFor(key));
    tray.setToolTip(`Claude Auto Shutdown · ${translate(lang, `tray.tip.${key}`)}`);
    tray.setContextMenu(buildTrayMenu(phase));
  }

  function buildTrayMenu(phase: Phase): Menu {
    const toggle: MenuItemConstructorOptions =
      phase === 'disarmed'
        ? { label: t('tray.arm'), click: arm }
        : phase === 'monitoring'
          ? { label: t('tray.stop'), click: () => controller.cancel() }
          : { label: t('tray.cancel'), click: () => controller.cancel() };
    return Menu.buildFromTemplate([
      { label: t('tray.open'), click: showWindow },
      { type: 'separator' },
      toggle,
      { label: t('tray.checkNow'), click: () => schedulePoll(0, true) },
      { type: 'separator' },
      {
        label: t('tray.quit'),
        click: () => {
          quitting = true;
          app.quit();
        },
      },
    ]);
  }

  function arm(): void {
    controller.arm();
    schedulePoll(0);
  }

  /** Schedules the next check. thorough = also inspect processes even while disarmed (user asked). */
  function schedulePoll(delayMs?: number, thorough = false): void {
    if (thorough) pollThoroughly = true;
    if (pollTimer) clearTimeout(pollTimer);
    pollTimer = null;
    // Not watching and no window (running in the background): nothing needs the result, since the
    // tray shows only the phase. Checks resume when the window opens or watching starts.
    if (controller.getPhase() === 'disarmed' && !windowOpen() && !pollThoroughly) {
      controller.setNextPollAt(null);
      return;
    }
    let ms = delayMs ?? controller.getSettings().pollIntervalSec * 1000;
    if (controller.getPhase() === 'countdown') ms = Math.min(ms, 15_000);
    controller.setNextPollAt(Date.now() + ms, ms);
    pushState(); // the window's ring counts down to this check
    pollTimer = setTimeout(() => {
      pollTimer = null;
      // nextPollAt stays in the past while the check runs: the ring shows it as empty.
      const options = pollThoroughly ? { thorough: true } : {};
      pollThoroughly = false;
      controller
        .poll(options)
        .catch((error: unknown) => reportError('app.checkFailed', error))
        .finally(() => schedulePoll());
    }, ms);
  }

  function createWindow(): BrowserWindow {
    const win = new BrowserWindow({
      width: 460,
      height: 680,
      minWidth: 380,
      minHeight: 480,
      show: false,
      title: 'Claude Auto Shutdown',
      icon: appIconPath,
      autoHideMenuBar: true,
      backgroundColor: '#0b0d10',
      webPreferences: {
        preload: path.join(__dirname, 'preload.js'),
        contextIsolation: true,
        nodeIntegration: false,
        sandbox: true,
        spellcheck: false,
      },
    });
    win.removeMenu();
    win.webContents.setWindowOpenHandler(() => ({ action: 'deny' }));
    win.webContents.on('will-navigate', (event) => event.preventDefault());
    win.webContents.on('render-process-gone', (_event, details) => {
      if (details.reason === 'clean-exit' || win.isDestroyed()) return;
      controller.addLog('warn', 'app.windowCrashed', { reason: details.reason });
      if (Date.now() - lastReloadAt > RELOAD_BACKOFF_MS) {
        lastReloadAt = Date.now();
        win.reload();
      }
    });
    win.once('ready-to-show', () => {
      // Test runs must not grab focus from whoever is using the machine.
      if (TEST_MODE) win.showInactive();
      else win.show();
    });
    win.on('close', () => {
      if (quitting || !controller.keepsRunningWithoutWindow()) return;
      // The window goes away to free its memory; the app carries on in the tray, from where it
      // is quit (the ^ arrow next to the clock, right-click, Quit).
      if (!toldAboutTray) {
        toldAboutTray = true;
        notify(msg(controller.getPhase() === 'disarmed' ? 'notify.trayIdle.title' : 'notify.tray.title'), msg('notify.tray.body'));
      }
    });
    win.on('closed', () => {
      if (mainWindow === win) mainWindow = null;
      onTop = false;
    });
    win.loadFile(path.join(__dirname, 'renderer', 'index.html')).catch((error: unknown) => reportError('app.windowLoadFailed', error));
    return win;
  }

  function windowOpen(): boolean {
    return mainWindow !== null && !mainWindow.isDestroyed();
  }

  function showWindow(): void {
    if (!mainWindow || mainWindow.isDestroyed()) {
      mainWindow = createWindow();
      // Checks pause while not watching in the background; armed checks never stopped.
      if (controller.getPhase() === 'disarmed') schedulePoll(0);
      return;
    }
    if (mainWindow.isMinimized()) mainWindow.restore();
    if (TEST_MODE) {
      mainWindow.showInactive();
      return;
    }
    mainWindow.show();
    mainWindow.focus();
  }

  function revealForCountdown(): void {
    showWindow();
    if (!TEST_MODE) mainWindow?.flashFrame(true);
  }

  async function capture(file: string): Promise<void> {
    if (!mainWindow || mainWindow.isDestroyed()) return;
    if (!mainWindow.isVisible()) mainWindow.showInactive();
    if (EXPAND) await mainWindow.webContents.executeJavaScript("document.querySelectorAll('details').forEach((d) => { d.open = true; })");
    // Grow the window to the page height so the screenshot shows everything.
    const height = Number(await mainWindow.webContents.executeJavaScript('document.documentElement.scrollHeight'));
    const [width] = mainWindow.getContentSize();
    if (Number.isFinite(height) && width) mainWindow.setContentSize(width, Math.min(Math.max(height, 600), 2400));
    await new Promise((resolve) => setTimeout(resolve, 600));
    const image = await mainWindow.webContents.capturePage();
    writeFileSync(file, image.toPNG());
    process.stdout.write(`captured ${file}\n`);
  }

  // ---- IPC: only the app's own window may call in ----------------------------------
  const fromAppWindow = (event: IpcMainInvokeEvent): boolean =>
    mainWindow !== null && !mainWindow.isDestroyed() && event.sender === mainWindow.webContents && (event.senderFrame?.url ?? '').startsWith('file:');
  const handle = (channel: string, fn: (...args: unknown[]) => unknown): void => {
    ipcMain.handle(channel, (event, ...args: unknown[]) => {
      if (!fromAppWindow(event)) throw new Error(`rejected IPC call: ${channel}`);
      return fn(...args);
    });
  };
  const isRecord = (value: unknown): value is Record<string, unknown> => value !== null && typeof value === 'object';
  handle('state:get', () => controller.state());
  handle('arm', () => arm());
  handle('disarm', () => controller.disarm('stop.user'));
  handle('cancel', () => controller.cancel());
  handle('poll-now', () => schedulePoll(0, true));
  handle('settings:update', (patch) => {
    const settings = controller.updateSettings(isRecord(patch) ? (patch as Partial<Settings>) : {});
    schedulePoll(0);
    return settings;
  });
  handle('settings:reset', () => {
    const settings = controller.resetSettings();
    schedulePoll(0);
    return settings;
  });
  handle('open-log-folder', async () => {
    await shell.openPath(userData);
  });

  // ---- lifecycle ------------------------------------------------------------------
  if (SMOKE) {
    app
      .whenReady()
      .then(async () => {
        const result = await detector.detect(controller.getSettings(), { forceSnapshot: true });
        process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
        logs.store?.close();
        app.exit(0);
      })
      .catch((error: unknown) => {
        process.stderr.write(`${String(error)}\n`);
        app.exit(1);
      });
    return;
  }

  app.on('second-instance', showWindow);
  app.on('before-quit', () => {
    quitting = true;
  });
  // While armed the app lives on in the tray without a window.
  app.on('window-all-closed', () => {
    if (quitting || !controller.keepsRunningWithoutWindow()) app.quit();
  });
  app.on('will-quit', () => logs.store?.close());

  app
    .whenReady()
    .then(() => {
      nativeTheme.themeSource = 'dark'; // the UI is dark only; this also darkens the title bar and native controls
      Menu.setApplicationMenu(null);
      // The page needs no browser permissions (camera, location, notifications, ...).
      session.defaultSession.setPermissionRequestHandler((_contents, _permission, callback) => callback(false));
      session.defaultSession.setPermissionCheckHandler(() => false);

      tray = new Tray(iconFor('disarmed'));
      tray.on('click', showWindow);
      updateTray('disarmed', false);
      if (!START_HIDDEN) mainWindow = createWindow();

      setInterval(() => controller.tick(), 1000);
      setInterval(() => logs.store?.prune(), 60 * 60 * 1000); // keep only the last 30 days
      powerMonitor.on('suspend', () => controller.addLog('info', 'app.suspending'));
      powerMonitor.on('resume', () => {
        controller.onResume();
        schedulePoll(0);
      });

      controller.addLog('info', DRY_RUN_FORCED ? 'app.startedDryRun' : 'app.started');
      if (logs.error) controller.addLog('warn', 'app.logDbFailed', { detail: logs.error });
      schedulePoll(0);
      if (AUTO_ARM) arm();
      if (CAPTURE_FILE) {
        setTimeout(() => {
          capture(CAPTURE_FILE).catch((error: unknown) => reportError('app.captureFailed', error));
        }, CAPTURE_DELAY_MS);
      }
      if (EXIT_AFTER_MS !== null) {
        setTimeout(() => {
          const log = controller.state().log.slice().reverse();
          process.stdout.write(`${JSON.stringify({ phase: controller.getPhase(), log })}\n`);
          quitting = true;
          logs.store?.close();
          app.exit(0);
        }, EXIT_AFTER_MS);
      }
    })
    .catch((error: unknown) => reportError('app.startupFailed', error));
}
