import { deflateSync } from 'node:zlib';

export type Rgb = readonly [number, number, number];

// ---- PNG / ICO encoding --------------------------------------------------------------

const CRC_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[n] = c >>> 0;
  }
  return table;
})();

function crc32(data: Buffer): number {
  let c = 0xffffffff;
  for (const byte of data) c = CRC_TABLE[(c ^ byte) & 0xff]! ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function pngChunk(type: string, data: Buffer): Buffer {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([length, body, crc]);
}

/** Encodes 8-bit RGBA pixels as a PNG file. */
export function encodePng(width: number, height: number, rgba: Uint8Array): Buffer {
  const stride = width * 4;
  const raw = Buffer.alloc((stride + 1) * height);
  for (let y = 0; y < height; y++) {
    raw[y * (stride + 1)] = 0; // filter: none
    Buffer.from(rgba.buffer, rgba.byteOffset + y * stride, stride).copy(raw, y * (stride + 1) + 1);
  }
  const header = Buffer.alloc(13);
  header.writeUInt32BE(width, 0);
  header.writeUInt32BE(height, 4);
  header[8] = 8; // bit depth
  header[9] = 6; // colour type: RGBA
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    pngChunk('IHDR', header),
    pngChunk('IDAT', deflateSync(raw)),
    pngChunk('IEND', Buffer.alloc(0)),
  ]);
}

/** Packs PNG images into a .ico file (PNG entries are valid since Windows Vista). */
export function encodeIco(images: ReadonlyArray<{ size: number; png: Buffer }>): Buffer {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(images.length, 4);
  const entries: Buffer[] = [];
  let offset = 6 + 16 * images.length;
  for (const { size, png } of images) {
    const entry = Buffer.alloc(16);
    entry.writeUInt8(size >= 256 ? 0 : size, 0);
    entry.writeUInt8(size >= 256 ? 0 : size, 1);
    entry.writeUInt16LE(1, 4); // colour planes
    entry.writeUInt16LE(32, 6); // bits per pixel
    entry.writeUInt32LE(png.length, 8);
    entry.writeUInt32LE(offset, 12);
    entries.push(entry);
    offset += png.length;
  }
  return Buffer.concat([header, ...entries, ...images.map((image) => image.png)]);
}

// ---- App icon -------------------------------------------------------------------------
// A dark rounded tile with a power symbol and a crescent moon ("shuts down at night").
// One geometry, two outputs: appIconSvg() for the SVG/favicon and renderAppIcon() for the
// PNG/ICO rasters (window, tray, .exe). Coordinates are in a 256 × 256 box.

const TILE = { inset: 8, radius: 56 };
const RING = { cx: 128, cy: 136, r: 66, gapDeg: 42 };
const BAR = { x: 128, top: 58, bottom: 118 };
const STROKE = 22;
const MOON = { cx: 200, cy: 56, r: 19, cutCx: 209, cutCy: 48, cutR: 16 };
const TILE_TOP: Rgb = [0x1d, 0x22, 0x2b];
const TILE_BOTTOM: Rgb = [0x0b, 0x0d, 0x10];
const GLYPH_START: Rgb = [0x5e, 0xf2, 0xb3];
const GLYPH_END: Rgb = [0x22, 0xb0, 0x78];
const MOON_COLOR: Rgb = [0xe9, 0xed, 0xf5];
const EDGE_HIGHLIGHT = 0.08;

export interface AppIconOptions {
  /** A solid glyph colour (tray states). Default: the green gradient. */
  glyph?: Rgb;
  /** Draw the crescent moon; it is too small to read at tray sizes. Default: true. */
  moon?: boolean;
}

const hex = (c: Rgb): string => `#${c.map((v) => v.toString(16).padStart(2, '0')).join('')}`;
const fixed = (n: number): string => String(Math.round(n * 100) / 100);
const clamp01 = (t: number): number => Math.min(1, Math.max(0, t));
const mix = (a: Rgb, b: Rgb, t: number): Rgb => {
  const k = clamp01(t);
  return [a[0] + (b[0] - a[0]) * k, a[1] + (b[1] - a[1]) * k, a[2] + (b[2] - a[2]) * k];
};

/** End points of the ring's opening at the top: side 1 = right, -1 = left. */
function ringEnd(side: 1 | -1): [number, number] {
  const angle = ((-90 + side * RING.gapDeg) * Math.PI) / 180;
  return [RING.cx + RING.r * Math.cos(angle), RING.cy + RING.r * Math.sin(angle)];
}

export function appIconSvg(options: AppIconOptions = {}): string {
  const moon = options.moon ?? true;
  const glyph = options.glyph ? hex(options.glyph) : 'url(#glyph)';
  const [rx, ry] = ringEnd(1);
  const [lx, ly] = ringEnd(-1);
  const size = 256 - 2 * TILE.inset;
  return [
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">',
    '  <!-- Generated by scripts/icons.ts from src/main/icon.ts -->',
    '  <defs>',
    '    <linearGradient id="tile" x1="0" y1="0" x2="0" y2="256" gradientUnits="userSpaceOnUse">',
    `      <stop offset="0" stop-color="${hex(TILE_TOP)}"/>`,
    `      <stop offset="1" stop-color="${hex(TILE_BOTTOM)}"/>`,
    '    </linearGradient>',
    '    <linearGradient id="glyph" x1="0" y1="0" x2="256" y2="256" gradientUnits="userSpaceOnUse">',
    `      <stop offset="0" stop-color="${hex(GLYPH_START)}"/>`,
    `      <stop offset="1" stop-color="${hex(GLYPH_END)}"/>`,
    '    </linearGradient>',
    ...(moon
      ? [
          '    <mask id="crescent">',
          '      <rect width="256" height="256" fill="#fff"/>',
          `      <circle cx="${MOON.cutCx}" cy="${MOON.cutCy}" r="${MOON.cutR}" fill="#000"/>`,
          '    </mask>',
        ]
      : []),
    '  </defs>',
    `  <rect x="${TILE.inset}" y="${TILE.inset}" width="${size}" height="${size}" rx="${TILE.radius}" fill="url(#tile)"/>`,
    `  <rect x="${TILE.inset + 0.5}" y="${TILE.inset + 0.5}" width="${size - 1}" height="${size - 1}" rx="${TILE.radius - 0.5}" fill="none" stroke="#fff" stroke-opacity="${EDGE_HIGHLIGHT}"/>`,
    `  <g fill="none" stroke="${glyph}" stroke-width="${STROKE}" stroke-linecap="round">`,
    `    <path d="M${fixed(rx)} ${fixed(ry)}A${RING.r} ${RING.r} 0 1 1 ${fixed(lx)} ${fixed(ly)}"/>`,
    `    <path d="M${BAR.x} ${BAR.top}V${BAR.bottom}"/>`,
    '  </g>',
    ...(moon ? [`  <circle cx="${MOON.cx}" cy="${MOON.cy}" r="${MOON.r}" fill="${hex(MOON_COLOR)}" mask="url(#crescent)"/>`] : []),
    '</svg>',
    '',
  ].join('\n');
}

/** Signed distance to the tile's rounded square (negative inside). */
function tileDistance(x: number, y: number): number {
  const center = 128;
  const half = 128 - TILE.inset - TILE.radius;
  const qx = Math.abs(x - center) - half;
  const qy = Math.abs(y - center) - half;
  return Math.hypot(Math.max(qx, 0), Math.max(qy, 0)) + Math.min(Math.max(qx, qy), 0) - TILE.radius;
}

const RIGHT_END = ringEnd(1);
const LEFT_END = ringEnd(-1);
const GAP_RAD = (RING.gapDeg * Math.PI) / 180;

function onGlyph(x: number, y: number): boolean {
  const half = STROKE / 2;
  // Ring with round caps: the arc outside the opening, plus discs at both ends.
  const fromTop = Math.atan2(x - RING.cx, -(y - RING.cy)); // 0 at the top, clockwise positive
  const ring =
    Math.abs(fromTop) >= GAP_RAD
      ? Math.abs(Math.hypot(x - RING.cx, y - RING.cy) - RING.r)
      : Math.min(Math.hypot(x - RIGHT_END[0], y - RIGHT_END[1]), Math.hypot(x - LEFT_END[0], y - LEFT_END[1]));
  if (ring <= half) return true;
  // Bar with round caps.
  const clampedY = Math.min(BAR.bottom, Math.max(BAR.top, y));
  return Math.hypot(x - BAR.x, y - clampedY) <= half;
}

const onMoon = (x: number, y: number): boolean =>
  Math.hypot(x - MOON.cx, y - MOON.cy) <= MOON.r && Math.hypot(x - MOON.cutCx, y - MOON.cutCy) > MOON.cutR;

/** Rasterises the icon to RGBA pixels with supersampled anti-aliasing. */
export function renderAppIconPixels(size: number, options: AppIconOptions = {}): Uint8Array {
  const moon = options.moon ?? true;
  const samples = size <= 32 ? 6 : 4;
  const scale = 256 / size;
  const pixels = new Uint8Array(size * size * 4);
  for (let py = 0; py < size; py++) {
    for (let px = 0; px < size; px++) {
      let r = 0;
      let g = 0;
      let b = 0;
      let covered = 0;
      for (let sy = 0; sy < samples; sy++) {
        for (let sx = 0; sx < samples; sx++) {
          const x = (px + (sx + 0.5) / samples) * scale;
          const y = (py + (sy + 0.5) / samples) * scale;
          const tile = tileDistance(x, y);
          if (tile > 0) continue;
          let color = mix(TILE_TOP, TILE_BOTTOM, y / 256);
          if (tile > -1) color = mix(color, [255, 255, 255], EDGE_HIGHLIGHT);
          if (onGlyph(x, y)) color = options.glyph ?? mix(GLYPH_START, GLYPH_END, (x + y) / 512);
          else if (moon && onMoon(x, y)) color = MOON_COLOR;
          r += color[0];
          g += color[1];
          b += color[2];
          covered++;
        }
      }
      if (covered === 0) continue;
      const i = (py * size + px) * 4;
      pixels[i] = Math.round(r / covered);
      pixels[i + 1] = Math.round(g / covered);
      pixels[i + 2] = Math.round(b / covered);
      pixels[i + 3] = Math.round((covered / (samples * samples)) * 255);
    }
  }
  return pixels;
}

export function renderAppIcon(size: number, options: AppIconOptions = {}): Buffer {
  return encodePng(size, size, renderAppIconPixels(size, options));
}

/** Sizes written into the .ico (Windows picks per DPI and context). */
export const ICO_SIZES = [16, 20, 24, 32, 40, 48, 64, 128, 256] as const;

export function renderAppIco(): Buffer {
  return encodeIco(ICO_SIZES.map((size) => ({ size, png: renderAppIcon(size) })));
}
